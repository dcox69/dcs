static uint8_t find_ansi_char(uint16_t unicode_char)
{
    if (unicode_char < 128)
    {
        return (uint8_t)unicode_char;
    }
    for (int i = 0; i < 128; i++)
    {
        if (current_codepage_table[i] == unicode_char)
        {
            return (uint8_t)(i + 128);
        }
    }
    return 0x3F; // '?' for chars not found
}

static int utf8_char_len(unsigned char byte)
{
    if (byte < 0x80) return 1;
    if ((byte & 0xE0) == 0xC0) return 2;
    if ((byte & 0xF0) == 0xE0) return 3;
    if ((byte & 0xF8) == 0xF0) return 4;
    return 0;
}

static uint32_t utf8_decode(const char *utf8_str, int *bytes_consumed)
{
    unsigned char *bytes     = (unsigned char *)utf8_str;
    int            len       = utf8_char_len(bytes[0]);
    uint32_t       codepoint = 0;

    *bytes_consumed          = len;

    switch (len)
    {
        case 1:
            return bytes[0];
        case 2:
            if ((bytes[1] & 0xC0) != 0x80)
            {
                *bytes_consumed = 1;
                return 0x3F;
            }
            codepoint = (bytes[0] & 0x1F) << 6;
            codepoint |= (bytes[1] & 0x3F);
            return codepoint;
        case 3:
            if ((bytes[1] & 0xC0) != 0x80 || (bytes[2] & 0xC0) != 0x80)
            {
                *bytes_consumed = 1;
                return 0x3F;
            }
            codepoint = (bytes[0] & 0x0F) << 12;
            codepoint |= (bytes[1] & 0x3F) << 6;
            codepoint |= (bytes[2] & 0x3F);
            return codepoint;
        case 4:
            if ((bytes[1] & 0xC0) != 0x80 || (bytes[2] & 0xC0) != 0x80 || (bytes[3] & 0xC0) != 0x80)
            {
                *bytes_consumed = 1;
                return 0x3F;
            }
            codepoint = (bytes[0] & 0x07) << 18;
            codepoint |= (bytes[1] & 0x3F) << 12;
            codepoint |= (bytes[2] & 0x3F) << 6;
            codepoint |= (bytes[3] & 0x3F);
            return codepoint;
        default:
            *bytes_consumed = 1;
            return 0x3F;
    }
}

static int utf8_encode(uint32_t codepoint, char *utf8_buffer)
{
    if (codepoint < 0x80)
    {
        utf8_buffer[0] = (char)codepoint;
        return 1;
    }
    else if (codepoint < 0x800)
    {
        utf8_buffer[0] = (char)(0xC0 | (codepoint >> 6));
        utf8_buffer[1] = (char)(0x80 | (codepoint & 0x3F));
        return 2;
    }
    else if (codepoint < 0x10000)
    {
        utf8_buffer[0] = (char)(0xE0 | (codepoint >> 12));
        utf8_buffer[1] = (char)(0x80 | ((codepoint >> 6) & 0x3F));
        utf8_buffer[2] = (char)(0x80 | (codepoint & 0x3F));
        return 3;
    }
    else if (codepoint < 0x110000)
    {
        utf8_buffer[0] = (char)(0xF0 | (codepoint >> 18));
        utf8_buffer[1] = (char)(0x80 | ((codepoint >> 12) & 0x3F));
        utf8_buffer[2] = (char)(0x80 | ((codepoint >> 6) & 0x3F));
        utf8_buffer[3] = (char)(0x80 | (codepoint & 0x3F));
        return 4;
    }
    return 0;
}

int ml_uw_utf8_to_win(const char *utf8_str, char *win_buffer, size_t buffer_size)
{
    if (!utf8_str || !win_buffer || buffer_size == 0)
    {
        return -1;
    }

    size_t input_len  = strlen(utf8_str);
    size_t output_pos = 0;
    size_t input_pos  = 0;

    while (input_pos < input_len && output_pos < buffer_size - 1)
    {
        int      bytes_consumed;
        uint32_t codepoint = utf8_decode(utf8_str + input_pos, &bytes_consumed);

        if (bytes_consumed == 0)
        {
            win_buffer[output_pos++] = '?';
            input_pos++;
        }
        else
        {
            input_pos += bytes_consumed;

            if (codepoint > 0xFFFF)
            {
                win_buffer[output_pos++] = '?';
            }
            else
            {
                uint8_t ansi_char        = find_ansi_char((uint16_t)codepoint);
                win_buffer[output_pos++] = (char)ansi_char;
            }
        }
    }

    win_buffer[output_pos] = '\0';
    return (int)output_pos;
}

bool ml_uw_utf8_is_valid(const char *utf8_str)
{
    if (!utf8_str)
    {
        return false;
    }

    size_t input_len = strlen(utf8_str);
    size_t pos       = 0;

    while (pos < input_len)
    {
        int bytes_consumed;
        utf8_decode(utf8_str + pos, &bytes_consumed);

        if (bytes_consumed == 0)
        {
            return false; // Invalid UTF-8 sequence
        }
        pos += bytes_consumed;
    }
    return true;
}


bool ml_uw_start_utf8_to_ansi_decoder(ml_uw_utf8_decoder_t *dec, const char *utf8_str)
{
    if (!utf8_str)
    {
        return false;
    }
    dec->utf8_str = utf8_str;
    dec->utf8_len = strlen(utf8_str);
    dec->index    = 0;
    return true;
}

char ml_uw_utf8_decode_next_ansi_char(ml_uw_utf8_decoder_t *dec)
{
    if (!dec || !dec->utf8_str)
    {
        return 0x00;
    }
    size_t input_len = dec->utf8_len;
    if (dec->index >= input_len)
    {
        return 0x00;
    }
    int      bytes_consumed;
    uint32_t codepoint = utf8_decode(dec->utf8_str + dec->index, &bytes_consumed);

    if (bytes_consumed == 0)
    {
        dec->index++;
        return 0x3F; // '?'
    }
    else
    {
        dec->index += bytes_consumed;
        if (codepoint > 0xFFFF)
        {
            return 0x3F; // '?'
        }
        else
        {
            uint8_t ansi_char = find_ansi_char((uint16_t)codepoint);
            return (char)ansi_char;
        }
    }
}

int ml_uw_win_to_utf8(const char *win_str, char *utf8_buffer, size_t buffer_size)
{
    if (!win_str || !utf8_buffer || buffer_size == 0)
    {
        return -1;
    }

    size_t input_len  = strlen(win_str);
    size_t output_pos = 0;

    for (size_t i = 0; i < input_len && output_pos < buffer_size - 4; i++)
    {
        unsigned char ansi_char = (unsigned char)win_str[i];
        uint32_t      codepoint;

        if (ansi_char < 128)
        {
            codepoint = ansi_char;
        }
        else
        {
            codepoint = current_codepage_table[ansi_char - 128];
        }

        int utf8_len = utf8_encode(codepoint, utf8_buffer + output_pos);
        if (utf8_len == 0)
        {
            utf8_buffer[output_pos++] = '?';
        }
        else
        {
            output_pos += utf8_len;
        }
    }

    utf8_buffer[output_pos] = '\0';
    return (int)output_pos;
}
